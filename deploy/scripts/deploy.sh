#!/usr/bin/env bash
#
# Brings the application to its desired state: runtime config, image, container,
# admin account, tailnet route. Assumes bootstrap.sh already provisioned the host.
#
# Replaying it is safe — the generated .env keeps its persisted secrets, the
# admin account is only created when none exists, and the tailnet route is left
# alone when it already points at the app.
#
# Inputs (via /run/cloudcli-deploy.env, written by the CI and deleted on exit):
#   CLOUDCLI_IMAGE           required — fully qualified image reference
#   GHCR_USERNAME/GHCR_TOKEN required for a private registry
#   CLOUDCLI_ADMIN_USERNAME  seeds the single account on the very first deploy
#   CLOUDCLI_ADMIN_PASSWORD
#   CLOUDCLI_JWT_SECRET      optional — generated and persisted when absent
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=lib/common.sh
. "${SCRIPT_DIR}/lib/common.sh"

INSTALL_DIR=${INSTALL_DIR:-/opt/cloudcli}
ENV_FILE="${INSTALL_DIR}/.env"
EPHEMERAL_ENV=/run/cloudcli-deploy.env
HEALTH_TIMEOUT_SECONDS=180
# Matches `container_name` in compose.yml — docker inspect and docker exec both
# address the container directly rather than through the compose project.
CONTAINER_NAME=cloudcli

compose() {
  docker compose --project-directory "${INSTALL_DIR}" -f "${INSTALL_DIR}/compose.yml" "$@"
}

cleanup() {
  rm -f "${EPHEMERAL_ENV}"
  docker logout ghcr.io >/dev/null 2>&1 || true
}

require_root
trap cleanup EXIT
load_env_file "${EPHEMERAL_ENV}"

HOST_PORT=${CLOUDCLI_HOST_PORT:-3001}

# Runtime knobs forwarded verbatim when the CI provides them. Anything outside
# this list stays out of the container's environment.
PASSTHROUGH_VARS=(
  ANTHROPIC_API_KEY
  ANTHROPIC_AUTH_TOKEN
  ANTHROPIC_BASE_URL
  OPENAI_API_KEY
  VOICE_API_KEY
  CONTEXT_WINDOW
  VITE_CONTEXT_WINDOW
)

read_persisted_value() {
  local key=$1
  [[ -f ${ENV_FILE} ]] || return 0
  sed -n "s/^${key}=//p" "${ENV_FILE}" | head -1
}

render_env_file() {
  log "Runtime configuration"

  # Rotating the signing secret on every deploy would log the operator out each
  # time, so an existing value wins unless the CI explicitly supplies one.
  local jwt_secret=${CLOUDCLI_JWT_SECRET:-}
  if [[ -z ${jwt_secret} ]]; then
    jwt_secret=$(read_persisted_value JWT_SECRET)
  fi
  if [[ -z ${jwt_secret} ]]; then
    jwt_secret=$(openssl rand -hex 48)
    ok "generated a new JWT secret"
  fi

  local tmp name
  tmp=$(mktemp "${INSTALL_DIR}/.env.XXXXXX")
  chmod 600 "${tmp}"
  {
    echo "# Generated by deploy.sh — edits are overwritten on the next run."
    echo "CLOUDCLI_IMAGE=${CLOUDCLI_IMAGE}"
    echo "CLOUDCLI_HOST_PORT=${HOST_PORT}"
    echo "JWT_SECRET=${jwt_secret}"
    echo "DATABASE_PATH=/home/node/.cloudcli/auth.db"
    for name in "${PASSTHROUGH_VARS[@]}"; do
      if [[ -n ${!name:-} ]]; then
        echo "${name}=${!name}"
      fi
    done
  } >"${tmp}"

  # Atomic swap: a half-written .env would take the container down on restart.
  mv "${tmp}" "${ENV_FILE}"
  ok "${ENV_FILE} written"
}

pull_image() {
  log "Image"
  if [[ -n ${GHCR_TOKEN:-} ]]; then
    require_env GHCR_USERNAME
    printf '%s' "${GHCR_TOKEN}" | docker login ghcr.io -u "${GHCR_USERNAME}" --password-stdin >/dev/null
    ok "authenticated against ghcr.io"
  fi
  compose pull --quiet
  ok "pulled ${CLOUDCLI_IMAGE}"
}

start_container() {
  log "Container"
  compose up -d --remove-orphans
  ok "compose applied"
}

wait_until_healthy() {
  log "Health"
  local deadline=$((SECONDS + HEALTH_TIMEOUT_SECONDS)) status
  while ((SECONDS < deadline)); do
    status=$(docker inspect -f '{{.State.Health.Status}}' "${CONTAINER_NAME}" 2>/dev/null || echo missing)
    case ${status} in
      healthy)
        ok "container healthy"
        return 0
        ;;
      unhealthy)
        break
        ;;
    esac
    sleep 3
  done

  compose logs --tail 60 app >&2 || true
  die "Container did not become healthy within ${HEALTH_TIMEOUT_SECONDS}s."
}

seed_admin_account() {
  log "Admin account"
  if [[ -z ${CLOUDCLI_ADMIN_USERNAME:-} || -z ${CLOUDCLI_ADMIN_PASSWORD:-} ]]; then
    skip "no credentials supplied — registration stays open to the first visitor"
    return 0
  fi

  # Runs inside the container so the JSON body is built by Node rather than by
  # string concatenation, and so the credentials travel as env vars, not argv.
  # The script is inlined because `node /dev/stdin` cannot read a pipe: Node
  # resolves it to /proc/<pid>/fd/0, which is a socket, not an openable file.
  docker exec -i \
    -e ADMIN_USERNAME="${CLOUDCLI_ADMIN_USERNAME}" \
    -e ADMIN_PASSWORD="${CLOUDCLI_ADMIN_PASSWORD}" \
    "${CONTAINER_NAME}" node -e "$(cat "${SCRIPT_DIR}/seed-admin.cjs")"
}

expose_on_tailnet() {
  log "Tailnet route"
  local target="http://127.0.0.1:${HOST_PORT}"

  if tailscale serve status 2>/dev/null | grep -q "127.0.0.1:${HOST_PORT}"; then
    skip "already served over HTTPS"
  elif ! tailscale serve --bg --https=443 "${target}"; then
    die "tailscale serve failed. Enable MagicDNS and HTTPS certificates for the tailnet in the Tailscale admin console, then rerun."
  else
    ok "served over HTTPS on the tailnet"
  fi

  # Best-effort display only: a failure to resolve the name must not fail a
  # deploy that already succeeded, and grep exits non-zero when it matches nothing.
  tailscale status --json 2>/dev/null \
    | grep -o '"DNSName":"[^"]*"' | head -1 | cut -d'"' -f4 \
    | sed 's|\.$||; s|^|  → https://|' || true
}

prune_images() {
  log "Cleanup"
  # Scoped to this image by label: the host may run unrelated containers whose
  # dangling layers are none of our business.
  docker image prune -f --filter "label=org.opencontainers.image.title=CloudCLI" >/dev/null
  ok "superseded CloudCLI images removed"
}

# Falling back to the persisted value lets the script be replayed on the box
# on its own — to restart after a reboot, or to roll back by editing the .env.
CLOUDCLI_IMAGE=${CLOUDCLI_IMAGE:-$(read_persisted_value CLOUDCLI_IMAGE)}
require_env CLOUDCLI_IMAGE

render_env_file
pull_image
start_container
wait_until_healthy
seed_admin_account
expose_on_tailnet
prune_images

log "Deployed"
